-- criacao da tabela de vendas de veiculos
CREATE TABLE sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL,
    cliente_id BIGINT NOT NULL,
    seller_id BIGINT NOT NULL,
    sale_price NUMERIC(38, 2) NOT NULL,
    sale_date TIMESTAMP NOT NULL,
    status VARCHAR(50) NOT NULL,
    payment_method VARCHAR(50),
    notes TEXT,
    cancellation_reason TEXT,
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT fk_sales_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles (id),
    CONSTRAINT fk_sales_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id),
    CONSTRAINT fk_sales_seller FOREIGN KEY (seller_id) REFERENCES users (id),
    CONSTRAINT chk_sales_status CHECK (status IN ('COMPLETED', 'CANCELLED')),
    CONSTRAINT chk_sales_payment_method CHECK (
        payment_method IS NULL OR
        payment_method IN ('A_VISTA', 'FINANCIAMENTO', 'CONSORCIO', 'PARCELADO')
    )
);

-- impede duas vendas ativas para o mesmo veiculo
CREATE UNIQUE INDEX uk_sales_active_vehicle
    ON sales (vehicle_id)
    WHERE status = 'COMPLETED';

-- indices para acelerar consultas do historico de vendas
CREATE INDEX idx_sales_seller_id ON sales (seller_id);
CREATE INDEX idx_sales_cliente_id ON sales (cliente_id);
CREATE INDEX idx_sales_status ON sales (status);
CREATE INDEX idx_sales_sale_date ON sales (sale_date);
