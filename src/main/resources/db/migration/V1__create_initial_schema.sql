-- criacao da tabela de marcas de veiculos
CREATE TABLE brands (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0
);

-- criacao da tabela de usuarios do sistema
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    telephone VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    user_type VARCHAR(50),
    user_status VARCHAR(50) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT uk_users_telephone UNIQUE (telephone),
    CONSTRAINT chk_users_user_type CHECK (user_type IS NULL OR user_type IN ('ROLE_ADMIN', 'ROLE_USER')),
    CONSTRAINT chk_users_user_status CHECK (user_status IN ('ACTIVE', 'INACTIVE'))
);

-- criacao da tabela de veiculos vinculados as marcas
CREATE TABLE vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    color VARCHAR(255) NOT NULL,
    vehicle_type VARCHAR(50) NOT NULL,
    price NUMERIC(38, 2) NOT NULL,
    brand_id BIGINT NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_vehicles_brand FOREIGN KEY (brand_id) REFERENCES brands (id),
    CONSTRAINT chk_vehicles_vehicle_type CHECK (vehicle_type IN ('CAR', 'MOTO'))
);

-- indices para acelerar consultas frequentes e chaves estrangeiras
CREATE INDEX idx_users_email ON users (email);
CREATE INDEX idx_users_telephone ON users (telephone);
CREATE INDEX idx_vehicles_brand_id ON vehicles (brand_id);
CREATE INDEX idx_brands_name ON brands (name);
