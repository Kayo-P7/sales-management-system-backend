CREATE TABLE registro_diario (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                 vendedor_id BIGINT NOT NULL,

                                 data DATE NOT NULL,

                                 pendencias_novas INTEGER,
                                 ligacoes INTEGER,
                                 negociacoes INTEGER,
                                 agendamentos INTEGER,
                                 chamadas_video INTEGER,
                                 clientes_em_loja INTEGER,
                                 fechamentos INTEGER,
                                 anuncios INTEGER,

                                 CONSTRAINT fk_registro_diario_vendedor
                                     FOREIGN KEY (vendedor_id)
                                         REFERENCES users(id),

                                 CONSTRAINT uk_registro_vendedor_data
                                     UNIQUE (vendedor_id, data),

                                 CONSTRAINT chk_pendencias_novas
                                     CHECK (pendencias_novas IS NULL OR pendencias_novas >= 0),

                                 CONSTRAINT chk_ligacoes
                                     CHECK (ligacoes IS NULL OR ligacoes >= 0),

                                 CONSTRAINT chk_negociacoes
                                     CHECK (negociacoes IS NULL OR negociacoes >= 0),

                                 CONSTRAINT chk_agendamentos
                                     CHECK (agendamentos IS NULL OR agendamentos >= 0),

                                 CONSTRAINT chk_chamadas_video
                                     CHECK (chamadas_video IS NULL OR chamadas_video >= 0),

                                 CONSTRAINT chk_clientes_em_loja
                                     CHECK (clientes_em_loja IS NULL OR clientes_em_loja >= 0),

                                 CONSTRAINT chk_fechamentos
                                     CHECK (fechamentos IS NULL OR fechamentos >= 0),

                                 CONSTRAINT chk_anuncios
                                     CHECK (anuncios IS NULL OR anuncios >= 0)
);