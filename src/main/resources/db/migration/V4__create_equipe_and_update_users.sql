
-- 1. Criar a tabela de equipes
CREATE TABLE equipe_tb (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           nome VARCHAR(255) NOT NULL,
                           supervisor_id BIGINT NOT NULL UNIQUE,

                           CONSTRAINT fk_equipe_supervisor
                               FOREIGN KEY (supervisor_id)
                                   REFERENCES users(id)
);

-- 2. Adicionar o relacionamento entre usuários e equipes
ALTER TABLE users
    ADD COLUMN equipe_id BIGINT;

ALTER TABLE users
    ADD CONSTRAINT fk_users_equipe
        FOREIGN KEY (equipe_id)
            REFERENCES equipe_tb(id);

-- 3. Atualizar os papéis permitidos
ALTER TABLE users
DROP CONSTRAINT chk_users_user_type;

ALTER TABLE users
    ADD CONSTRAINT chk_users_user_type
        CHECK (
            user_type IS NULL OR
            user_type IN (
                          'ROLE_ADMIN',
                          'ROLE_SUPERVISOR',
                          'ROLE_VENDEDOR'
                )
            );
